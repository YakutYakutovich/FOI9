# Заменя похожих букв и цифр в номере
def true_letters_num(number):
    if len(number) < 6:
        return number

    number = list(number)
    num_alpha = {
        "0": "O",
        "8": "B",
        "4": "M",
        "1": "T",
        "2": "E",
        "7": "T"
    }
    for i in (0, 4, 5):
        if number[i] in num_alpha:
            number[i] = num_alpha[number[i]]

    alpha_num = {
        "O": "0",
        "B": "8",
        "K": "4",
        "T": "1",
        "E": "5",
        "Y": "4",
        "A": "1"
    }
    for i in (1, 2, 3):
        if number[i] in alpha_num:
            number[i] = alpha_num[number[i]]

    if len(number) > 6:
        number = number[:6]

    number = ''.join(number)
    return number


# Замена похожих букв на цифры в регионе и сверка с валидными регионами
def true_letters_reg(number):
    if len(number) < 2:
        return ""
    number = list(number)
    if len(number) >= 4:
        number = number[-3:]

    alpha_num = {
        "O": "0",
        "B": "8",
        "K": "4",
        "T": "1",
        "E": "5",
        "Y": "4",
        "A": "1"
    }

    for i in range(len(number)):
        if number[i] in alpha_num:
            number[i] = alpha_num[number[i]]

    number = "".join(number)

    for number in (number, number[1:]):
        if number in valid_region_codes:
            return number

    return number
